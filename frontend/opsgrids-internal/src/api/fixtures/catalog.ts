const flat = (id: string, whole: number): Price => ({
  price_id: id,
  kind: "flat",
  amount_minor: rupees(whole),
  currency: INR,
  unit: null,
  unit_price_micros: null,
  meter_key: null,
});

const perSeat = (id: string, wholePerSeat: number): Price => ({
  price_id: id,
  kind: "per_seat",
  amount_minor: rupees(wholePerSeat),
  currency: INR,
  unit: "seat",
  unit_price_micros: null,
  meter_key: null,
});

