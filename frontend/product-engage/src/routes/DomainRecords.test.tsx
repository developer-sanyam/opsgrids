import { render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, describe, expect, it, vi } from "vitest";

import type { DnsRecordOut } from "@/api/types";
import { DomainRecordsTable } from "./DomainRecords";

/**
 * The record table is retyped into a registrar, so what is pinned here is fidelity and the
 * required/recommended split — and now the provider-aware shapes: SPF's "add vs edit vs merge"
 * distinction, and DKIM/DMARC's instructional placeholders where no value is knowable.
 *
 * A value that is reflowed, truncated or prettified is a record that will never verify, and the
 * customer will blame their registrar. A DMARC row that reads as a blocker sends them to argue
 * about `p=` with their security team before they can send at all — `fold_domain_status` folds
 * from the required records alone, and this table has to say so.
 */

/** A Google Workspace domain mid-setup: SPF is up, DKIM is not, DMARC is unpublished and
 *  optional — the shape the service produces most often. */
const RECORDS: DnsRecordOut[] = [
  {
    kind: "spf",
    type: "TXT",
    fqdn: "vaayu-freight.example.com",
    registrar_name: "@",
    value: "v=spf1 include:_spf.google.com ~all",
    suggested_value: "v=spf1 include:_spf.google.com ~all",
    required: true,
    status: "verified",
    instruction: "Publish one SPF TXT record at your domain's apex that includes _spf.google.com.",
  },
  {
    kind: "dkim",
    type: "TXT",
    fqdn: "google._domainkey.vaayu-freight.example.com",
    registrar_name: "google._domainkey",
    value: "(generated by Google Workspace)",
    suggested_value: null,
    required: true,
    status: "missing",
    instruction:
      "In the Google Admin console, go to Apps -> Google Workspace -> Gmail -> Authenticate " +
      "email, generate a key, publish the TXT value it gives you here, then click Start " +
      "authentication.",
  },
  {
    kind: "dmarc",
    type: "TXT",
    fqdn: "_dmarc.vaayu-freight.example.com",
    registrar_name: "_dmarc",
    value: "v=DMARC1; p=none; rua=mailto:dmarc@vaayu-freight.example.com",
    suggested_value: null,
    required: false,
    status: "missing",
    instruction: "Recommended: publish a DMARC policy. It never blocks sending.",
  },
];

function mount(records = RECORDS) {
  render(<DomainRecordsTable records={records} domainName="vaayu-freight.example.com" />);
  return userEvent.setup();
}

/** The row whose row header names this record. */
function rowFor(name: RegExp): HTMLElement {
  const row = screen.getByRole("rowheader", { name }).closest("tr");
  if (row === null) throw new Error(`No row for ${String(name)}`);
  return row;
}

/**
 * jsdom ships no clipboard, and `userEvent.setup()` installs one of its own — so a stub has to go
 * in *after* the user is set up, or it is the one that gets overwritten.
 */
function stubClipboard(clipboard: { writeText: () => Promise<void> } | undefined) {
  Object.defineProperty(navigator, "clipboard", { value: clipboard, configurable: true });
}

afterEach(() => {
  vi.restoreAllMocks();
  Reflect.deleteProperty(navigator, "clipboard");
});

describe("the DNS record table", () => {
  it("renders one row per record, with its type, registrar name and host exactly as the service sent them", () => {
    mount();

    const dkim = rowFor(/DKIM/);
    expect(within(dkim).getByText("TXT")).toBeTruthy();
    expect(within(dkim).getByText("google._domainkey")).toBeTruthy();
    expect(within(dkim).getByText("google._domainkey.vaayu-freight.example.com")).toBeTruthy();

    const spf = rowFor(/SPF/);
    expect(within(spf).getByText("@")).toBeTruthy();
    expect(within(spf).getByText("vaayu-freight.example.com")).toBeTruthy();

    // Three records, plus the header row.
    expect(screen.getAllByRole("row")).toHaveLength(4);
  });

  it("never renders a return-path or tracking row — OpsGrids publishes neither", () => {
    mount();
    expect(screen.queryByText(/Return path/)).toBeNull();
    expect(screen.queryByText(/Tracking/)).toBeNull();
  });

  it("marks each record required, and DMARC as recommended and not blocking", () => {
    mount();

    expect(within(rowFor(/SPF/)).getByText("Required")).toBeTruthy();
    expect(within(rowFor(/DKIM/)).getByText("Required")).toBeTruthy();
    expect(
      within(rowFor(/DMARC/)).getByText("Recommended — doesn't block sending"),
    ).toBeTruthy();
  });

  it("states each record's own state, in words rather than by colour", () => {
    mount();

    expect(within(rowFor(/SPF/)).getByText("Published")).toBeTruthy();
    expect(within(rowFor(/DKIM/)).getByText("Not found")).toBeTruthy();
    expect(within(rowFor(/DMARC/)).getByText("Not found")).toBeTruthy();
  });

  it("counts the required records only, so an unpublished DMARC never reads as the blocker", () => {
    mount();
    // One of the two required records is up; DMARC is in neither half of that fraction.
    expect(screen.getByText("1 of 2 required records found.")).toBeTruthy();
  });

  it("shows Google's DKIM value as generated elsewhere, with no copy control for it", () => {
    mount();
    expect(screen.getByText("(generated by Google Workspace)")).toBeTruthy();
    expect(screen.queryByRole("button", { name: /Copy DKIM.*value/ })).toBeNull();
  });

  it("shows the provider-specific DKIM setup instructions", () => {
    mount();
    expect(screen.getByText(/Google Admin console/)).toBeTruthy();
  });

  describe("SPF, whose value carries a verb the customer must act on", () => {
    it("says 'Add this record' when nothing is published yet", () => {
      mount([
        {
          kind: "spf",
          type: "TXT",
          fqdn: "vaayu-freight.example.com",
          registrar_name: "@",
          value: "v=spf1 include:_spf.google.com ~all",
          suggested_value: "v=spf1 include:_spf.google.com ~all",
          required: true,
          status: "missing",
          instruction: "No SPF record was found. Publish one at your domain's apex.",
        },
      ]);
      expect(screen.getByText("Add this record:")).toBeTruthy();
    });

    it("says to edit the existing record, not add a second one, on a mismatch", () => {
      mount([
        {
          kind: "spf",
          type: "TXT",
          fqdn: "vaayu-freight.example.com",
          registrar_name: "@",
          value: "v=spf1 mx ~all",
          suggested_value: "v=spf1 mx include:_spf.google.com ~all",
          required: true,
          status: "mismatch",
          instruction: "Edit your existing SPF record to this value — don't add a second one",
        },
      ]);
      expect(
        screen.getByText("Edit your existing SPF record to this value — don't add a second one:"),
      ).toBeTruthy();
      expect(screen.getByText("v=spf1 mx include:_spf.google.com ~all")).toBeTruthy();
    });

    it("explains merging and shows the merged value when there is more than one record", () => {
      mount([
        {
          kind: "spf",
          type: "TXT",
          fqdn: "vaayu-freight.example.com",
          registrar_name: "@",
          value: "v=spf1 mx ~all",
          suggested_value: "v=spf1 mx include:_spf.google.com ~all",
          required: true,
          status: "multiple",
          instruction:
            "Your domain has 2 SPF records; a domain may have only one. Merge them into one.",
        },
      ]);
      expect(screen.getByText("Your domain has more than one SPF record")).toBeTruthy();
      expect(
        screen.getByText(
          "Your domain has 2 SPF records; a domain may have only one. Merge them into one.",
        ),
      ).toBeTruthy();
      expect(screen.getByText("Replace every one of your SPF records with this single one:")).toBeTruthy();
    });
  });

  it("copies a value verbatim, which is the whole reason the button is there", async () => {
    const user = mount();
    const writeText = vi.fn().mockResolvedValue(undefined);
    stubClipboard({ writeText });

    await user.click(screen.getByRole("button", { name: /Copy SPF record/ }));

    expect(writeText).toHaveBeenCalledWith("v=spf1 include:_spf.google.com ~all");
    expect(await screen.findByText("Copied")).toBeTruthy();
  });

  it("copies a registrar name as well as a value, because both are typed into the registrar", async () => {
    const user = mount();
    const writeText = vi.fn().mockResolvedValue(undefined);
    stubClipboard({ writeText });

    await user.click(screen.getByRole("button", { name: /Copy DMARC.*name/ }));

    expect(writeText).toHaveBeenCalledWith("_dmarc");
  });

  it("survives a browser with no clipboard rather than leaving a button that throws", async () => {
    const user = mount();
    // What an insecure origin looks like, where `navigator.clipboard` is simply not there.
    stubClipboard(undefined);

    await user.click(screen.getByRole("button", { name: /Copy SPF record/ }));

    // The value is still on screen to select by hand, and nothing claims it was copied.
    expect(screen.getByText("v=spf1 include:_spf.google.com ~all")).toBeTruthy();
    expect(screen.queryByText("Copied")).toBeNull();
  });
});
