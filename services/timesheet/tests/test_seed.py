"""The demo seed produces the expected rows, and is idempotent.

Drives `tools/demo/seed_pulseboard.py`'s timesheet stage directly against a tenant-bound
session (the seed module is importable and side-effect-free at load), so this proves the same
grid the live Timesheets screen renders lands correctly: twelve person-weeks for the current
week, cells generated by the ported `buildCells`, statuses index-aligned with the fixtures, and
the deterministic person UUID the project service's roster shares.
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

import pytest

from app import domain, selectors
from platform_core.auth import Scope
from tests.helpers import ctx_for

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "tools" / "demo"))
import seed_pulseboard

pytestmark = pytest.mark.integration

TODAY = date.today()
MONDAY = domain.week_monday(TODAY)


class TestDemoSeed:
    async def test_seed_inserts_a_week_per_person(self, session, org_id) -> None:
        ctx = ctx_for(org_id, "pulseboard.time.timesheet.write", Scope.ORG)
        async with session.begin():
            counts = await seed_pulseboard.seed_timesheet(session, ctx, today=TODAY)
        assert counts["timesheets"] == 12
        assert counts["skipped"] == 0
        # Five weekdays of entries per person, plus the weekend-crunch Saturdays
        # (person indexes 0, 5 and 10; weekday hours are always > 0 for these capacities).
        assert counts["entries"] == 12 * 5 + 3

    async def test_seed_is_idempotent(self, session, org_id) -> None:
        ctx = ctx_for(org_id, "pulseboard.time.timesheet.write", Scope.ORG)
        async with session.begin():
            await seed_pulseboard.seed_timesheet(session, ctx, today=TODAY)
        async with session.begin():
            second = await seed_pulseboard.seed_timesheet(session, ctx, today=TODAY)
        assert second["timesheets"] == 0
        assert second["entries"] == 0
        assert second["skipped"] == 12

    async def test_seeded_grid_mirrors_the_fixture_arithmetic(self, session, org_id) -> None:
        """The cells are the ported `buildCells`: same hours, statuses index-aligned."""
        ctx = ctx_for(org_id, "pulseboard.time.timesheet.write", Scope.ORG)
        async with session.begin():
            await seed_pulseboard.seed_timesheet(session, ctx, today=TODAY)

        read = ctx_for(org_id, "pulseboard.time.timesheet.read", Scope.ORG)
        sheets = await selectors.weeks_for(session, read, MONDAY)
        assert [s.person_ref for s in sheets] == [f"p{i:02d}" for i in range(1, 13)]
        assert [s.status for s in sheets] == seed_pulseboard.TIMESHEET_STATUS

        entries = await selectors.entries_by_sheet(session, org_id, [s.id for s in sheets])
        by_ref = {s.person_ref: selectors.row_out(s, entries.get(s.id, [])) for s in sheets}

        week = domain.week_dates(MONDAY)
        expected = seed_pulseboard.build_cells(0, 20, week)  # p01, capacity 20
        row = by_ref["p01"]
        assert row.week_start == MONDAY
        assert [c.entered_hours for c in row.cells] == [e for _, e, _ in expected]
        assert [c.billable_hours for c in row.cells] == [b for _, _, b in expected]
        # p01 (index 0) is one of the two weekend-crunch people: Saturday is worked.
        assert row.cells[5].entered_hours > 0
        assert row.cells[6].entered_hours == 0

    async def test_seeded_person_uuid_matches_the_roster(self, session, org_id) -> None:
        """The UUID this stage stores is the one the project service's roster row carries."""
        ctx = ctx_for(org_id, "pulseboard.time.timesheet.write", Scope.ORG)
        async with session.begin():
            await seed_pulseboard.seed_timesheet(session, ctx, today=TODAY)
        sheet = await selectors.get_week(session, org_id, "p04", MONDAY)
        assert sheet is not None
        assert sheet.person_id == seed_pulseboard.person_uuid(org_id, "p04")
        assert sheet.capacity_minutes == 40 * 60
