"""enable row level security

Tenant isolation stops being a convention every query has to remember and becomes something the
database enforces. ADR-0002.

Three things had to be true before this migration could do anything at all, and all three landed
first, deliberately, in their own slice:

1. Policies exist — this file.
2. The application connects as a **NOBYPASSRLS** role. A superuser bypasses row security
   unconditionally and `FORCE` cannot override it, so policies written before the role split
   would have been decoration that looked like enforcement.
3. Something sets the tenant GUC. `get_tenant_session` binds every request transaction to the
   caller's organization as its first statement.

Classification is written out per table rather than generated by looping over "every table with
an `organization_id` column". That loop gets four tables wrong here: it misses `organizations`,
whose tenant column is `id`; it misses the two child tables that have no such column; and it
would wrongly policy `processed_events`, defeating consumer idempotency in silence. Which tables
are tenant-scoped is a security decision and belongs in a diff a human read.

Revision ID: e5a1c92ce2dc
Revises: 702ada644525
Create Date: 2026-08-22 22:23:54.749277
"""

from __future__ import annotations

from collections.abc import Sequence

from alembic import op

revision: str = "e5a1c92ce2dc"
down_revision: str | None = "702ada644525"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

SCHEMA = "account"
APP_ROLE = "opsgrids_account"

#: Tables carrying `organization_id`. The ordinary case.
TENANT_TABLES = (
    "audit_logs",
    "invitations",
    "locations",
    "memberships",
    "org_domains",
    "org_units",
    "outbox",
    "roles",
)

#: Children with no `organization_id` of their own, policied through their parent. Without
#: this, a session that guessed a `role_id` could read another tenant's grant set.
CHILD_TABLES = {
    "membership_roles": ("memberships", "membership_id"),
    "role_permissions": ("roles", "role_id"),
}

#: Deliberately **not** policied, each for its own reason:
#:
#: - `users` — global identity by design; email is unique platform-wide so one person can hold
#:   memberships in several organizations. A membership-EXISTS policy is not viable: Postgres
#:   applies SELECT policies to `INSERT ... RETURNING`, and SQLAlchemy flushes `User` that way,
#:   so `add_member` would fail on its first statement. Guarded instead by a test asserting no
#:   route reads it without joining memberships (ADR-0002, decision 3).
#: - `permissions` — the platform's vocabulary, not a customer's. Every organization reads the
#:   whole catalogue on purpose.
#: - `processed_events` — has no organization column at all. Any policy makes every idempotency
#:   lookup return nothing, so a redelivered event is processed twice, silently.
UNPOLICIED = ("users", "permissions", "processed_events")


def _enable(table: str) -> None:
    """Enable, and FORCE.

    `FORCE` is **not** what makes this work — verified: a NOBYPASSRLS role that does not own the
    table is filtered by a plain `ENABLE`. It is set for the two futures where it does matter: a
    table created accidentally by the app role, which would then own it and silently bypass its
    own policy, and a later decision to drop `BYPASSRLS` from the admin role.
    """
    op.execute(f"ALTER TABLE {SCHEMA}.{table} ENABLE ROW LEVEL SECURITY")
    op.execute(f"ALTER TABLE {SCHEMA}.{table} FORCE ROW LEVEL SECURITY")


def upgrade() -> None:
    # `nullif(..., '')` is not tidying. Once a transaction that set the GUC locally has ended,
    # the next transaction on the same session reads it back as an empty string rather than
    # NULL — verified. Without `nullif`, `''::uuid` raises a cast error; with it the predicate
    # is false and the query returns nothing. Fail-quiet is the deliberate choice, with the
    # application asserting loudly instead (ADR-0002 §4).
    op.execute(
        f"""
        CREATE OR REPLACE FUNCTION {SCHEMA}.current_org() RETURNS uuid
            LANGUAGE sql STABLE PARALLEL SAFE
        AS $$ SELECT nullif(current_setting('app.organization_id', true), '')::uuid $$
        """
    )

    for table in TENANT_TABLES:
        _enable(table)
        # WITH CHECK is not optional. USING is evaluated against existing rows and is not
        # applied to the new row of an INSERT, so without it a tenant could insert a row
        # belonging to somebody else — invisible to them, fully visible to the victim.
        op.execute(
            f"""
            CREATE POLICY tenant_isolation ON {SCHEMA}.{table}
                FOR ALL TO {APP_ROLE}
                USING      (organization_id = {SCHEMA}.current_org())
                WITH CHECK (organization_id = {SCHEMA}.current_org())
            """
        )

    # The tenant *is* the row. INSERT becomes impossible for a tenant by construction — you
    # cannot name a GUC for an id that does not exist yet — which is correct: bringing an
    # organization into existence is a platform operation and runs as the admin role.
    _enable("organizations")
    op.execute(
        f"""
        CREATE POLICY tenant_isolation ON {SCHEMA}.organizations
            FOR ALL TO {APP_ROLE}
            USING      (id = {SCHEMA}.current_org())
            WITH CHECK (id = {SCHEMA}.current_org())
        """
    )

    for table, (parent, fk) in CHILD_TABLES.items():
        _enable(table)
        op.execute(
            f"""
            CREATE POLICY tenant_isolation ON {SCHEMA}.{table}
                FOR ALL TO {APP_ROLE}
                USING (EXISTS (
                    SELECT 1 FROM {SCHEMA}.{parent} p
                     WHERE p.id = {table}.{fk}
                       AND p.organization_id = {SCHEMA}.current_org()))
                WITH CHECK (EXISTS (
                    SELECT 1 FROM {SCHEMA}.{parent} p
                     WHERE p.id = {table}.{fk}
                       AND p.organization_id = {SCHEMA}.current_org()))
            """
        )


def downgrade() -> None:
    """The deliberate undo, and the slowest of three rollbacks.

    For an incident there are faster levers: `ALTER ROLE opsgrids_account BYPASSRLS` restores
    service in one statement with no lock and leaves the policies intact for diagnosis, and
    pointing the DSN back at the admin role needs no database change at all. This one takes a
    brief ACCESS EXCLUSIVE lock per table and touches no rows.
    """
    for table in (*TENANT_TABLES, "organizations", *CHILD_TABLES):
        op.execute(f"DROP POLICY IF EXISTS tenant_isolation ON {SCHEMA}.{table}")
        op.execute(f"ALTER TABLE {SCHEMA}.{table} NO FORCE ROW LEVEL SECURITY")
        op.execute(f"ALTER TABLE {SCHEMA}.{table} DISABLE ROW LEVEL SECURITY")

    op.execute(f"DROP FUNCTION IF EXISTS {SCHEMA}.current_org()")
