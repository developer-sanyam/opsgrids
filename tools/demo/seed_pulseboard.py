def _seeded(n: float) -> float:
    """`fixtures.ts seeded`: a stable pseudo-random in [0,1) — same sin trick, same values."""
    x = math.sin(n) * 10000
    return x - math.floor(x)


def _round_half(n: float) -> float:
    """`fixtures.ts roundHalf`: JS `Math.round(n*2)/2` — half always rounds up."""
    return math.floor(n * 2 + 0.5) / 2


def build_cells(
    person_index: int, capacity_hours: int, week: list[date]
) -> list[tuple[date, float, float]]:
    """`fixtures.ts buildCells`, ported: (date, entered_hours, billable_hours) per day."""
    daily_target = capacity_hours / 5
    ratio = BILLABLE_RATIO[person_index] if person_index < len(BILLABLE_RATIO) else 0.85
    cells: list[tuple[date, float, float]] = []
    for day, when in enumerate(week):
        if day >= 5:
            # A little weekend crunch for two people; everyone else is off.
            crunch = person_index % 5 == 0 and day == 5
            entered = _round_half(2 + _seeded(person_index * 13 + day) * 3) if crunch else 0.0
            cells.append((when, entered, entered))
            continue
        jitter = _seeded(person_index * 7 + day) * 2 - 1  # -1..+1
        entered = max(0.0, _round_half(daily_target + jitter))
        billable = min(entered, _round_half(entered * ratio))
        cells.append((when, entered, billable))
    return cells


