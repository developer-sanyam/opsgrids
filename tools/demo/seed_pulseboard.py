"""Seed the PulseBoard demo data for the demo org, mirroring the SPA fixtures.

PulseBoard spans three services — project (people, engagements, board tasks), timesheet (the
weekly grid) and standup (the daily check-ins) — so this seeder runs in three **stages**, one
per service, each inside that service's directory as a subprocess (every service exposes a
top-level `app`, so one process can import only one of them — the same constraint the other
seeders live under):

    seed_pulseboard.py project   services/project   <org_id> <admin_user_id> <admin_membership_id>
    seed_pulseboard.py timesheet services/timesheet <org_id> <admin_user_id> <admin_membership_id>
    seed_pulseboard.py standup   services/standup   <org_id> <admin_user_id> <admin_membership_id>

Each stage mirrors the service's tests/conftest: it connects as that service's NOBYPASSRLS app
role and binds the tenant GUC on every transaction (the GUC is transaction-local), so writes go
through the same row-level-security path a real request does, and through the real `services.*`
write paths — so people, projects, tasks, timesheet weeks and standup entries all land with an
audit row and an outbox event, exactly as the live product produces them.

The dataset is the SPA's `frontend/product-pulseboard/src/api/fixtures.ts` and
`src/data/people.ts`, one-for-one: the same 12 people, 14 engagements and 22 board cards,
current-week timesheets generated by a byte-for-byte port of the fixtures' `buildCells`, and
today's 9 standups — so the live screens look like the fixtures the user already approved.
Money is carried in US cents (integer minor units), exactly the fixtures' figures. Dates are
relative: timesheets fill the week containing "today", standups land on "today" itself, just as
the fixtures build theirs around their `TODAY` constant.

The person behind a timesheet row or a standup entry is the project service's roster person.
No stage reads another's schema (that is the whole point of the split), so the shared person
UUID is **deterministic**: `uuid5(NAMESPACE_URL, "opsgrids:pulseboard:person:<org>:<ref>")` —
every stage derives the same id from the same ref, and re-running never mints a new identity.

Idempotent: a person ref / project code / task key / person-week / person-day that already
exists is skipped, so re-running never duplicates.
"""

